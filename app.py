# 3. ВКЛАДКА: КАЛЬКУЛЯТОР БЕЛКА
# ==============================================================================
with tab_calc:
    st.header("🧮 Персональный калькулятор дневной нормы белка")
    st.write("Введите ваши параметры, чтобы узнать оптимальное количество белка в день с учётом роста, веса, возраста и цели.")

    in_col1, in_col2 = st.columns(2)
    with in_col1:
        weight = st.number_input("Ваш текущий вес (кг):", min_value=30.0, max_value=220.0, value=70.0, step=0.5)
        height = st.number_input("Ваш рост (см):", min_value=120, max_value=230, value=175, step=1)
        age = st.number_input("Ваш возраст (лет):", min_value=14, max_value=100, value=28, step=1)

    with in_col2:
        gender = st.radio("Пол:", ["Мужской", "Женский"], horizontal=True)
        activity = st.selectbox("Уровень физической активности:", [
            "Низкий (сидячий образ жизни, без тренировок)",
            "Умеренный (фитнес / прогулки 2–3 раза в неделю)",
            "Высокий (силовые или кардио тренировки 4–6 раз в неделю)"
        ])
        goal = st.selectbox("Главная цель:", [
            "Поддержание здоровья и формы",
            "Похудение (сохранение мышц на дефиците)",
            "Набор мышечной массы"
        ])

    height_m = height / 100
    bmi = weight / (height_m ** 2)
    if bmi > 28:
        ideal_weight = 24 * (height_m ** 2)
        calc_weight = ideal_weight + 0.25 * (weight - ideal_weight)
    else:
        calc_weight = weight

    coeff = 1.2
    if "Умеренный" in activity:
        coeff += 0.3
    elif "Высокий" in activity:
        coeff += 0.5

    if "Похудение" in goal:
        coeff += 0.3
    elif "Набор" in goal:
        coeff += 0.4

    if gender == "Женский":
        coeff -= 0.1

    age_note = "В вашем возрасте усвоение белка находится на оптимальном уровне."
    if age >= 50:
        coeff *= 1.12
        age_note = "После 50 лет снижается чувствительность мышц к аминокислотам, поэтому норма увеличена на 12% для защиты от потери мышечной массы."
    elif age < 21:
        coeff *= 1.05
        age_note = "В молодом возрасте организм активно растёт и восстанавливается, поэтому заложен небольшой запас (+5%)."

    daily_protein = round(calc_weight * coeff)
    min_protein = round(daily_protein * 0.9)
    max_protein = round(daily_protein * 1.1)
    per_meal = round(daily_protein / 3.5)

    st.markdown("---")

    res1, res2, res3 = st.columns(3)
    res1.metric("🎯 Ваша норма белка в день", f"{daily_protein} г", f"Диапазон: {min_protein}–{max_protein} г")
    res2.metric("🍽️ Оптимально за 1 приём пищи", f"~{per_meal} г", "При 3–4 приёмах пищи в день")
    res3.metric("⚖️ Ваш индекс массы тела (ИМТ)", f"{bmi:.1f}", "Учтён в формуле расчёта")

    st.info(f"💡 **Учёт возраста ({age} лет):** {age_note}")

    g_chart1, g_chart2 = st.columns(2)

    with g_chart1:
        comp_df = pd.DataFrame({
            "Уровень потребления": [
                "Минимум ВОЗ (чтобы не болеть)",
                "Средний рацион обычного человека",
                "ВАША ИНДИВИДУАЛЬНАЯ НОРМА"
            ],
            "Грамм белка в день": [round(calc_weight * 0.8), round(calc_weight * 1.0), daily_protein]
        })
        fig_comp = px.bar(
            comp_df,
            x="Уровень потребления",
            y="Грамм белка в день",
            text="Грамм белка в день",
            color="Уровень потребления",
            title="📊 Сравнение вашей нормы с базовыми показателями",
            color_discrete_sequence=["#B0BEC5", "#90CAF9", "#2E7D32"]
        )
        fig_comp.update_traces(textposition="outside")
        fig_comp.update_layout(showlegend=False, height=380, yaxis_range=[0, max(daily_protein * 1.3, 120)])
        st.plotly_chart(fig_comp, use_container_width=True)

