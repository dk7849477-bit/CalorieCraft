    st.markdown("---")
    st.subheader("📖 Как правильно потреблять белок в течение дня?")
    st.markdown("""
    * **Распределяйте белок равномерно.** Организм эффективнее всего использует белок для восстановления тканей, когда вы получаете по **25–40 г белка за каждый основной приём пищи** (завтрак, обед, ужин), а не съедаете всю норму за один раз вечером.
    * **Сочетайте животные и растительные источники.** Животный белок (мясо, рыба, яйца, молочные продукты) содержит полный набор незаменимых аминокислот, а растительный (бобовые, крупы, орехи, тофу) обогащает рацион клетчаткой и витаминами.
    * **Не забывайте о воде и овощах.** При увеличении доли белка в рационе важно пить достаточно чистой воды и добавлять свежие овощи или зелень к каждому приёму пищи для комфортного пищеварения.
    * **Регулярность важнее идеальных цифр.** Отклонение в пределах **±10–15 г** от вашей дневной нормы абсолютно нормально — ориентируйтесь на средний показатель за неделю.
    """)
